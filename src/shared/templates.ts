import { newDocument, RichNode } from "./model";
export const p = (text: string, styleName = "Normal"): RichNode => ({
  type: "paragraph",
  attrs: { styleName },
  content: text ? [{ type: "text", text }] : undefined,
});
export const h = (text: string, level = 1): RichNode => ({
  type: "heading",
  attrs: { level, styleName: `Heading ${level}`, id: crypto.randomUUID() },
  content: [{ type: "text", text }],
});
const list = (items: string[]): RichNode => ({
  type: "bulletList",
  content: items.map((t) => ({ type: "listItem", content: [p(t)] })),
});
const table = (rows: string[][]): RichNode => ({
  type: "table",
  content: rows.map((r, i) => ({
    type: "tableRow",
    content: r.map((t) => ({
      type: i ? "tableCell" : "tableHeader",
      attrs: { colspan: 1, rowspan: 1, colwidth: null },
      content: [p(t)],
    })),
  })),
});
